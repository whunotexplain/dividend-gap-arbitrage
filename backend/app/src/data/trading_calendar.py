"""
Утилиты для работы с торговым календарём MOEX.
Отдельный файл, потому что "сдвиг на N торговых дней" — универсальная
операция, не привязанная конкретно к дивидендным событиям
(пригодится и для фичи days_to_cutoff, и для других расчётов).
"""
import pandas as pd


def shift_trading_days(price_index: pd.DatetimeIndex, date: pd.Timestamp, n: int) -> pd.Timestamp | None:
    """
    Сдвигает дату на n торговых дней НАЗАД, используя реальный индекс
    торговых дат конкретного тикера (учитывает выходные и праздники MOEX,
    а не календарные дни).

    price_index — отсортированный DatetimeIndex торговых дней (df_price.index).
    date — дата, от которой считаем сдвиг.
    n — сколько торговых дней назад сдвинуться (n >= 1).

    Возвращает None, если сдвиг выходит за пределы доступной истории цен
    (например date слишком близко к началу имеющихся данных).
    """
    if n < 1:
        raise ValueError("n должно быть >= 1")

    # Все торговые дни строго ДО указанной даты
    prior_days = price_index[price_index < date]

    if len(prior_days) < n:
        return None  # недостаточно истории, чтобы отсчитать n дней назад

    # n-й с конца торговый день перед date
    return prior_days[-n]