# backend/app/src/data/corporate_actions.py
"""
Реестр известных корпоративных действий, искажающих расчёт div_yield.
Ведётся вручную — MOEX ISS не отдаёт эту информацию в удобном
программном виде, поэтому список собирается через целенаправленную
проверку "подозрительных" событий (см. detect_anomalies.py).

Два вида искажений:

1. НЕУЧТЁННЫЙ СПЛИТ/КОНСОЛИДАЦИЯ (STOCK_SPLITS)
   MOEX задним числом корректирует ИСТОРИЧЕСКИЕ свечи под будущий
   сплит/консолидацию, а dividend_per_share остаётся в старых
   единицах. Из-за этого div_yield искажается в разы для событий
   ДО даты корп. действия.
   Фикс: делим dividend_per_share на split_ratio для событий
   с cutoff_date СТРОГО РАНЬШЕ даты сплита.
   split_ratio > 1 означает дробление (цена ÷ratio, напр. PLZL 1:10 → 10)
   split_ratio < 1 означает консолидацию (цена ×|1/ratio|)

2. ОТМЕНЁННЫЕ ДИВИДЕНДЫ (CANCELLED_DIVIDENDS)
   MOEX хранит в истории дивидендов и те выплаты, которые совет
   директоров РЕКОМЕНДОВАЛ, но акционеры на собрании ОТКЛОНИЛИ.
   Формально в API это выглядит как обычная запись с cutoff_date,
   хотя реального дивидендного гэпа не было — то падение цены,
   которое произошло, вызвано новостным шоком "отказались платить",
   а не механической просадкой после отсечки. Это другое по своей
   природе рыночное событие, не относится к задаче предсказания
   дивидендных гэпов — событие полностью исключается из датасета.
"""

# (ticker, split_date) -> split_ratio
# Подтверждено вручную через веб-поиск, см. историю разработки.
STOCK_SPLITS = {
    ("PLZL", "2025-03-26"): 10,      # дробление 1:10 (цена ÷10)
    # ("VTBR", "2024-07-15"): 1/5000,  # TODO: обратный сплит 5000:1 —
    #   подтверждена ДАТА и коэффициент, но НЕ подтверждено, действительно
    #   ли div_yield=27.4% на событии 2025-07-11 — артефакт или реальная
    #   рекордная выплата ВТБ после многолетнего перерыва. Нужна отдельная
    #   проверка реальной доходности этой конкретной выплаты, прежде чем
    #   включать корректировку — иначе можем испортить корректные данные.
}

# (ticker, cutoff_date) -> причина
# Дивиденд был рекомендован СД, но отклонён на собрании акционеров —
# реальной выплаты и дивидендного гэпа не было.
CANCELLED_DIVIDENDS = {
    ("GAZP", "2022-07-20"): "Дивиденды за 2021 год (52.53 руб.) отклонены "
                             "на годовом собрании акционеров 30.06.2022 — "
                             "впервые с 1998 года. Выплаты не было.",
}


def is_cancelled(ticker: str, cutoff_date) -> bool:
    key = (ticker, str(cutoff_date)[:10])
    return key in CANCELLED_DIVIDENDS


def get_split_adjustment(ticker: str, cutoff_date) -> float:
    """
    Возвращает коэффициент, на который нужно ПОДЕЛИТЬ dividend_per_share,
    если событие произошло ДО даты сплита этого тикера. Иначе — 1.0
    (без изменений).
    """
    cutoff_str = str(cutoff_date)[:10]
    for (t, split_date), ratio in STOCK_SPLITS.items():
        if t == ticker and cutoff_str < split_date:
            return ratio
    return 1.0